#!/bin/bash
# drain-probes.sh (genbt.sh on the host) <osd-binary> : print a bpftrace script with uprobes on the autotuner of that binary
BIN=$1; OFF=/root/hot/offsets2.txt
nm "$BIN" | awk '$2 ~ /^[TW]$/ {print $1, $3}' > /tmp/nm.raw
nm -C "$BIN" | awk '$2 ~ /^[TW]$/ {addr=$1; $1=""; $2=""; sub(/^  /,""); print addr "\t" $0}' > /tmp/nm.dem
python3 - "$BIN" "$OFF" <<'PY'
import sys, re
BIN, OFF = sys.argv[1], sys.argv[2]
raw = {}
for l in open('/tmp/nm.raw'):
    a, s = l.split(); raw.setdefault(a, s)
dem = {}
for l in open('/tmp/nm.dem'):
    a, d = l.rstrip('\n').split('\t', 1); dem.setdefault(d, a)
want = {
 'balance':   'PriorityCache::Manager::balance()',
 'mreq':      'BlueStore::MempoolThread::MempoolCache::request_cache_bytes(PriorityCache::Priority, unsigned long) const',
 'kreq':      'rocksdb_cache::BinnedLRUCache::request_cache_bytes(PriorityCache::Priority, unsigned long) const',
 'mcommit':   'BlueStore::MempoolThread::MempoolCache::commit_cache_size(unsigned long)',
 'kcommit':   'rocksdb_cache::BinnedLRUCache::commit_cache_size(unsigned long)',
 'dsum':      'BlueStore::MempoolThread::DataCache::_sum_bins(unsigned int, unsigned int) const',
 'msum':      'BlueStore::MempoolThread::MetaCache::_sum_bins(unsigned int, unsigned int) const',
 'dused':     'BlueStore::MempoolThread::DataCache::_get_used_bytes() const',
 'mused':     'BlueStore::MempoolThread::MetaCache::_get_used_bytes() const',
 'trim':      'TwoQBufferCacheShard::_trim_to(unsigned long)',
 'resize':    'BlueStore::MempoolThread::_resize_shards(bool)',
}
sym = {}
for k, d in want.items():
    a = dem.get(d)
    if a is None or a not in raw: sys.exit('symbol not found: ' + d)
    sym[k] = '0x' + a.lstrip('0')   # address form: bpftrace mis-resolves some exported C++ names
off = {}
for l in open(OFF):
    m = re.match(r'/\*\s+(\d+)\s+\|\s+\d+ \*/\s+.*\b(max|buffer_bytes|num);', l)
    if m: off.setdefault(m.group(2), int(m.group(1)))
if 'buffer_bytes' not in off: sys.exit('offsets not found in ' + OFF + ': ' + str(off))
off.setdefault('max', -1)
P = 'uprobe:%s:' % BIN; R = 'uretprobe:%s:' % BIN
print('// generated by genbt.sh for %s; shard offsets max=%d buffer_bytes=%d' % (BIN, off['max'], off['buffer_bytes']))
for k, d in want.items(): print('// %s = %s  %s' % (k, sym[k], d))
print('BEGIN { printf("START %s\\n", strftime("%s", nsecs)); }')
print(P + sym['balance'] + ' { printf("BAL %d %s\\n", pid, strftime("%s", nsecs)); }')
for tag, k in (('REQ', 'mreq'), ('KREQ', 'kreq')):
    print(P + sym[k] + ' { @rq_this[tid] = arg0; @rq_pri[tid] = arg1; }')
    print(R + sym[k] + ' { printf("%s %%d %%lx %%d %%ld\\n", pid, @rq_this[tid], @rq_pri[tid], (int64)retval); }' % tag)
for tag, k in (('COMMIT', 'mcommit'), ('KCOMMIT', 'kcommit')):
    print(P + sym[k] + ' { @cm_this[tid] = arg0; }')
    print(R + sym[k] + ' { printf("%s %%d %%lx %%ld\\n", pid, @cm_this[tid], (int64)retval); }' % tag)
print(P + sym['dsum'] + ' /@data_this[pid] == 0/ { @data_this[pid] = arg0; printf("DTHIS %d %lx\\n", pid, arg0); }')
print(P + sym['msum'] + ' /@meta_this[pid] == 0/ { @meta_this[pid] = arg0; printf("MTHIS %d %lx\\n", pid, arg0); }')
print(R + sym['dused'] + ' { @data_used[pid] = retval; }')
print(R + sym['mused'] + ' { @meta_used[pid] = retval; }')
print(P + sym['trim'] + ' { @lim[pid, arg0] = arg1; @held[pid, arg0] = *(uint64 *)(arg0 + %d); }' % off['buffer_bytes'])
print(P + sym['resize'] + ' /arg1 == 1/ { printf("RESIZE %d %s data_used=%lu meta_used=%lu\\n", pid, strftime("%s", nsecs), @data_used[pid], @meta_used[pid]); print(@lim); print(@held); }')
print('END { printf("END %s\\n", strftime("%s", nsecs)); clear(@rq_this); clear(@rq_pri); clear(@cm_this); clear(@data_this); clear(@meta_this); clear(@data_used); clear(@meta_used); clear(@lim); clear(@held); }')
PY
